export function translate(lang, key, vars) {
  const text = dict[lang]?.[key] ?? dict.en[key] ?? key;
  if (!vars) return text;
  return String(text).replace(/\{(\w+)\}/g, (m, k) => (vars[k] != null ? vars[k] : m));
}

export default dict;
